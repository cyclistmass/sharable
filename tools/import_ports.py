"""Imports Crest's bell-buoy ports (Mauro, 2026-10-11: 1.5x bigger, a surprise shape, docks kept) into res/drawable-nodpi
and writes app/src/main/java/com/mauro/wgbg/PortArt.kt.

Source: C:/Users/mauro/wgbg-art/ports3d/buoy/port_<type>_tilt_<0..7>.png, 256x256 RGBA at 193 px per hex unit, anchored at
the centre; type = 3to1, timber, clay, fleece, grain, stone. The docks stay drawn in code.

Usage: py tools/import_ports.py
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/res/drawable-nodpi"
KT = ROOT / "app/src/main/java/com/mauro/wgbg/PortArt.kt"
SRC = Path(r"C:/Users/mauro/wgbg-art/ports3d/buoy")
TYPES = ["3to1", "timber", "clay", "fleece", "grain", "stone"]   # GENERIC, then resources in engine order

for old in OUT.glob("port_*_tilt_*.webp"):
    old.unlink()
names = {}
for t in TYPES:
    names[t] = []
    for i in range(8):
        n = f"port_{t}_tilt_{i}"
        Image.open(SRC / f"port_{t}_tilt_{i}.png").convert("RGBA").save(OUT / f"{n}.webp", quality=88, method=6)
        names[t].append(n)
lines = ["package com.mauro.wgbg", "", "// Generated by tools/import_ports.py: do not edit by hand.", "",
         "/** The bell-buoy ports: 8 tilt steps each (tilt = 0.96 * i / 7), 256 px frames at 193 px per hex unit, centred. */",
         "object PortArt {",
         "    /** Index 0 is the 3:1 port (Port.GENERIC); 1..5 are Timber, Clay, Fleece, Grain, Stone (resource + 1). */",
         "    val TYPES = listOf("]
for t in TYPES:
    lines.append("        listOf(" + ", ".join(f"R.drawable.{n}" for n in names[t]) + "),")
lines += ["    )", "", "    fun index(portType: Int) = portType + 1", "}", ""]
KT.write_text("\n".join(lines), encoding="utf8")
print(f"{sum(len(v) for v in names.values())} port sprites, PortArt.kt written")
