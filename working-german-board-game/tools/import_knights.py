"""Imports the 3D Age of Chivalry knights (Crest renders of Codex's Blender models, Mauro's pick 2026-10-11) into
res/drawable-nodpi and writes app/src/main/java/com/mauro/wgbg/KnightArt.kt with the resource lists.

Source: C:/Users/mauro/wgbg-art/knights3d/set1/steps8/knight_<theme>_l<n>[_trim]_tilt8_<0..7>.png, 256x256 RGBA at
193 px per hex unit with the base contact point at the centre, the same contract as the buildings: a BODY layer
tinted to the player's colour and an untinted TRIM layer on top. Inactive knights reuse the same frames with the
body dimmed in code. Old imported files are removed first so nothing stale stays in res/.

Usage: py tools/import_knights.py
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/res/drawable-nodpi"
KT = ROOT / "app/src/main/java/com/mauro/wgbg/KnightArt.kt"
SRC = Path(r"C:/Users/mauro/wgbg-art/knights3d/set1/steps8")
THEMES = ["normal", "pirate"]
STEPS = 8

for old in OUT.glob("kn_*.webp"):
    old.unlink()

sets = {}
for theme in THEMES:
    for level in (1, 2, 3):
        for layer, mid in (("body", ""), ("trim", "_trim")):
            names = []
            for i in range(STEPS):
                name = f"kn_{theme}_l{level}{mid}_tilt_{i}"
                Image.open(SRC / f"knight_{theme}_l{level}{mid}_tilt8_{i}.png").convert("RGBA").save(OUT / f"{name}.webp", quality=90, method=6)
                names.append(name)
            sets[(theme, level, layer)] = names


def kt_list(names):
    return "listOf(" + ", ".join(f"R.drawable.{n}" for n in names) + ")"


lines = [
    "package com.mauro.wgbg",
    "",
    "// Generated by tools/import_knights.py: do not edit by hand.",
    "",
    "/**",
    " * The 3D knights: per level (1, 2, 3 figures) a tintable body and an untinted trim layer, 8 tilt steps",
    " * (tilt = 0.96 * i / 7), 256 px frames at 193 px per hex unit with the base contact point at the centre.",
    " */",
    "object KnightArt {",
]
for theme in THEMES:
    for level in (1, 2, 3):
        lines.append(f"    val {theme.upper()}_L{level} = BuildingArt.Piece({kt_list(sets[(theme, level, 'body')])},")
        lines.append(f"        {kt_list(sets[(theme, level, 'trim')])})")
lines += [
    "",
    "    /** Levels 1, 2, 3 for the theme. */",
    "    fun levels(pirate: Boolean) = if (pirate) listOf(PIRATE_L1, PIRATE_L2, PIRATE_L3) else listOf(NORMAL_L1, NORMAL_L2, NORMAL_L3)",
    "}",
    "",
]
KT.write_text("\n".join(lines), encoding="utf8")
print(f"{sum(len(v) for v in sets.values())} sprites, KnightArt.kt written")
